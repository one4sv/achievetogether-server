-- dev 0.6.4: one-off plans, separate from habit_planned.
create table public.one_off_plans (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references public.users(id) on delete cascade,
    name text not null check (length(btrim(name)) between 1 and 160),
    description text not null default '',
    plan_date date not null,
    start_time time,
    end_time time,
    timezone text not null default 'Europe/Moscow',
    place text not null default '',
    kind text not null default 'personal' check (kind in ('personal','shared')),
    completion_mode text not null default 'personal' check (completion_mode in ('personal','shared')),
    visibility text not null default 'nobody' check (visibility in ('nobody','contacts','all')),
    join_mode text not null default 'invite' check (join_mode in ('invite','request','open')),
    status text not null default 'upcoming' check (status in ('upcoming','completed','canceled')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint one_off_plan_times check (start_time is null or end_time is null or end_time >= start_time),
    constraint one_off_plan_personal_mode check (kind <> 'personal' or completion_mode = 'personal')
);
create table public.one_off_plan_members (
    plan_id bigint not null references public.one_off_plans(id) on delete cascade,
    user_id uuid not null references public.users(id) on delete cascade,
    status text not null default 'pending' check (status in ('pending','accepted','declined')),
    invited_by uuid references public.users(id) on delete set null,
    joined_at timestamptz,
    primary key (plan_id,user_id)
);
create table public.one_off_plan_completions (
    plan_id bigint not null references public.one_off_plans(id) on delete cascade,
    user_id uuid not null references public.users(id) on delete cascade,
    completed_at timestamptz not null default now(),
    primary key (plan_id,user_id)
);
create table public.one_off_plan_chat_links (
    plan_id bigint not null references public.one_off_plans(id) on delete cascade,
    chat_id bigint not null references public.chats(id) on delete cascade,
    linked_by uuid references public.users(id) on delete set null,
    primary key (plan_id,chat_id)
);
create index one_off_plans_owner_date on public.one_off_plans(owner_id,plan_date);
create index one_off_plan_members_user_status on public.one_off_plan_members(user_id,status);
create index one_off_plan_chat_links_chat on public.one_off_plan_chat_links(chat_id);
alter table public.one_off_plans enable row level security;
alter table public.one_off_plan_members enable row level security;
alter table public.one_off_plan_completions enable row level security;
alter table public.one_off_plan_chat_links enable row level security;
-- No public RLS policies: only the authenticated AT backend service role may access plans.
revoke all on public.one_off_plans,public.one_off_plan_members,public.one_off_plan_completions,public.one_off_plan_chat_links from anon,authenticated;
grant select,insert,update,delete on public.one_off_plans,public.one_off_plan_members,public.one_off_plan_completions,public.one_off_plan_chat_links to service_role;
grant usage,select on sequence public.one_off_plans_id_seq to service_role;
