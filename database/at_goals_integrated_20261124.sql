-- Integrated personal goals. New model: no separate goals navigation or public Data API.
create table public.at_goals (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references public.users(id) on delete cascade,
    name text not null check (length(btrim(name)) between 1 and 160),
    description text not null default '' check (length(description) <= 1200),
    due_date date,
    progress_mode text not null default 'manual' check (progress_mode in ('manual','metric','milestones','combined')),
    status text not null default 'active' check (status in ('active','paused','completed','canceled','archived')),
    manual_progress numeric(7,2) not null default 0 check (manual_progress between 0 and 100),
    metric_start numeric(16,4) not null default 0,
    metric_target numeric(16,4) not null default 100,
    metric_current numeric(16,4) not null default 0,
    metric_unit text not null default '' check (length(metric_unit) <= 24),
    metric_share numeric(4,3) not null default 0.5 check (metric_share between 0 and 1),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint at_goals_metric_range check (progress_mode not in ('metric','combined') or metric_start <> metric_target)
);
create index at_goals_owner_created on public.at_goals(owner_id,created_at desc);
create table public.at_goal_stages (
    id bigint generated by default as identity primary key,
    goal_id bigint not null references public.at_goals(id) on delete cascade,
    title text not null check (length(btrim(title)) between 1 and 160),
    weight numeric(10,3) not null default 1 check (weight > 0 and weight <= 10000),
    position integer not null default 0,
    completed_at timestamptz
);
create index at_goal_stages_position on public.at_goal_stages(goal_id,position,id);
create table public.at_goal_habit_links (
    goal_id bigint not null references public.at_goals(id) on delete cascade,
    habit_id bigint not null references public.habits(id) on delete cascade,
    primary key (goal_id,habit_id)
);
create index at_goal_habit_links_habit on public.at_goal_habit_links(habit_id);
create table public.at_goal_plan_links (
    goal_id bigint not null references public.at_goals(id) on delete cascade,
    plan_id bigint not null references public.one_off_plans(id) on delete cascade,
    primary key (goal_id,plan_id)
);
create index at_goal_plan_links_plan on public.at_goal_plan_links(plan_id);
create table public.at_goal_events (
    id bigint generated by default as identity primary key,
    goal_id bigint not null references public.at_goals(id) on delete cascade,
    actor_id uuid references public.users(id) on delete set null,
    action text not null,
    details jsonb,
    created_at timestamptz not null default now()
);
create index at_goal_events_goal on public.at_goal_events(goal_id,id desc);
alter table public.at_goals enable row level security;
alter table public.at_goal_stages enable row level security;
alter table public.at_goal_habit_links enable row level security;
alter table public.at_goal_plan_links enable row level security;
alter table public.at_goal_events enable row level security;
revoke all on public.at_goals,public.at_goal_stages,public.at_goal_habit_links,public.at_goal_plan_links,public.at_goal_events from anon,authenticated;
grant select,insert,update,delete on public.at_goals,public.at_goal_stages,public.at_goal_habit_links,public.at_goal_plan_links,public.at_goal_events to service_role;
grant usage,select on sequence public.at_goals_id_seq,public.at_goal_stages_id_seq,public.at_goal_events_id_seq to service_role;
