-- Personal goals v1. Access is server/service-role only: no direct anonymous or user REST access.
create table if not exists public.goals (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references public.users(id) on delete cascade,
    name text not null check (length(btrim(name)) between 1 and 160),
    description text not null default '' check (length(description) <= 1200),
    due_date date,
    progress_mode text not null default 'manual' check (progress_mode in ('manual','metric','milestones','combined')),
    status text not null default 'active' check (status in ('draft','active','paused','completed','canceled','archived')),
    manual_progress numeric(7,2) not null default 0 check (manual_progress between 0 and 100),
    metric_start numeric(18,4) not null default 0,
    metric_target numeric(18,4) not null default 100,
    metric_current numeric(18,4) not null default 0,
    metric_unit text not null default '' check (length(metric_unit) <= 24),
    metric_share numeric(4,3) not null default 0.7 check (metric_share between 0 and 1),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint goal_metric_range check (progress_mode not in ('metric','combined') or metric_start <> metric_target)
);
create index if not exists goals_owner_created on public.goals(owner_id, created_at desc);

create table if not exists public.goal_milestones (
    id bigint generated by default as identity primary key,
    goal_id bigint not null references public.goals(id) on delete cascade,
    title text not null check (length(btrim(title)) between 1 and 160),
    weight numeric(10,3) not null default 1 check (weight > 0 and weight <= 10000),
    position int not null default 0,
    completed_at timestamptz,
    completed_by uuid references public.users(id) on delete set null
);
create index if not exists goal_milestones_goal_position on public.goal_milestones(goal_id, position);

create table if not exists public.goal_habit_links (
    goal_id bigint not null references public.goals(id) on delete cascade,
    habit_id bigint not null references public.habits(id) on delete cascade,
    primary key (goal_id, habit_id)
);
create table if not exists public.goal_plan_links (
    goal_id bigint not null references public.goals(id) on delete cascade,
    plan_id bigint not null references public.one_off_plans(id) on delete cascade,
    primary key (goal_id, plan_id)
);
create table if not exists public.goal_progress_events (
    id bigint generated by default as identity primary key,
    goal_id bigint not null references public.goals(id) on delete cascade,
    actor_id uuid references public.users(id) on delete set null,
    action text not null,
    old_value jsonb,
    new_value jsonb,
    created_at timestamptz not null default now()
);
create index if not exists goal_events_recent on public.goal_progress_events(goal_id, id desc);

alter table public.goals enable row level security;
alter table public.goal_milestones enable row level security;
alter table public.goal_habit_links enable row level security;
alter table public.goal_plan_links enable row level security;
alter table public.goal_progress_events enable row level security;
revoke all on public.goals, public.goal_milestones, public.goal_habit_links, public.goal_plan_links, public.goal_progress_events from anon, authenticated;
grant select, insert, update, delete on public.goals, public.goal_milestones, public.goal_habit_links, public.goal_plan_links, public.goal_progress_events to service_role;
grant usage, select on sequence public.goals_id_seq, public.goal_milestones_id_seq, public.goal_progress_events_id_seq to service_role;
